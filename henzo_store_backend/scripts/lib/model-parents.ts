function inchVariants(entries: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const key of Object.keys(entries)) {
    const noInch = key.replace(/\s*\d{1,2}(?:\.\d+)?in\b/g, '').trim();
    if (noInch && noInch !== key && !entries[noInch]) {
      out[key] = noInch;
    }
  }
  return out;
}

const MODEL_PARENT_ALL: Record<string, string> = {
  ...MODEL_PARENT,
  ...inchVariants(MODEL_PARENT),
};

export function modelParentChain(model: string): string[] {
  const chain: string[] = [];
  const seen = new Set<string>([model]);
  let cur = model;

  for (let i = 0; i < 5; i++) {
    const parent = MODEL_PARENT_ALL[cur];
    if (!parent || seen.has(parent)) break;
    chain.push(parent);
    seen.add(parent);
    cur = parent;
  }
  return chain;
}
