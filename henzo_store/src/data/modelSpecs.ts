export function specModelKey(name: string): string {
  const trimmed = name.replace(/\s+/g, ' ').trim();
  const hit = MODEL_KEYS_BY_LENGTH.find((k) =>
    trimmed.toLowerCase().startsWith(k.toLowerCase()),
  );
  return hit ?? fallbackModelKey(trimmed);
}

function fallbackModelKey(name: string): string {
  return name
    .replace(/\s+\d+(?:\.\d+)?\s*(?:GB|TB|MB)\b/gi, ' ')
    .replace(/\s*\d{1,2}(?:\.\d+)?\s*(?:"|inch)\b/gi, ' ')
    .replace(
      /\s+(?:[A-Z][a-z]+\s+){0,2}?(?:Black|White|Gray|Grey|Silver|Titanium Gray|Natural Titanium|Deep Blue|Eclipse Gray|Tonal Silver|Moonlight White|Platinum Silver|Graphite Gray|Lunar Gray|Storm Gray|Arctic White|Titanium Black|Silver Shadow|Cobalt Violet|Forest Green|Obsidian|Porcelain|Hazel|MX Stone|Pale Gray|Carbon Black|Graphite|Chromium|Sandstone|Mango|Snow|Blue|Sand)\s*$/i,
      ' ',
    )
    .replace(/\s+/g, ' ')
    .trim();
}

export function specCapacity(name: string): string {
  const m = name.match(/\b(\d+(?:\.\d+)?\s*(?:GB|TB|MB))\b/i);
  return m ? m[1].replace(/\s+/g, ' ').toUpperCase() : '';
}

export function specsForProduct(name: string): {
  specs: Record<string, string>;
  missing: boolean;
} {
  const key = specModelKey(name);
  const template = MODEL_SPECS[key];
  const cap = specCapacity(name);
  if (!template) return { specs: {}, missing: true };

  const specs: Record<string, string> = {};
  for (const [k, v] of Object.entries(template)) {
    specs[k] = v.replace(/\{\{CAP\}\}/g, cap || '—');
  }
  return { specs, missing: false };
}

export const SPEC_MODEL_KEYS = Object.keys(MODEL_SPECS);

export function normalizeProductName(name: string): string {
  const seenInch = new Set<string>();
  const seenCap = new Set<string>();
  const out = name
    .split(' ')
    .filter((t) => {
      const inch = t.match(/^(\d{1,2}(?:\.\d+)?)(?:"|inch|in)$/i);
      if (inch) {
        if (seenInch.has(inch[1])) return false;
        seenInch.add(inch[1]);
        return true;
      }
      const cap = t.match(/^(\d+(?:\.\d+)?)(GB|TB|MB)$/i);
      if (cap) {
        const k = cap[1].toUpperCase() + cap[2].toUpperCase();
        if (seenCap.has(k)) return false;
        seenCap.add(k);
        return true;
      }
      return true;
    })
    .join(' ');
  return out.replace(/\s+/g, ' ').trim();
}

const MODEL_KEYS_BY_LENGTH = SPEC_MODEL_KEYS.slice().sort(
  (a, b) => b.length - a.length,
);
